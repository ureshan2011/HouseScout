// Prediction engine — the inference half of the model trained by scripts/hedonic.py,
// running in the browser off public/model.json.
//
//   valuation()        modelled value, confidence band, feature-by-feature breakdown
//   pricePosition()    asking price vs modelled value
//   rentForecast()     weekly room rent and whole-house rent
//   growthForecast()   mean-reverting growth path with a widening band
//   negotiationRoom()  expected room to move, by sale method and staleness
//   dealScore()        composite 0-100 opportunity ranking
//
// Every number traces to a coefficient or a documented rule. Nothing here is
// generated by a language model.

const BASE_PATH = process.env.NEXT_PUBLIC_BASE_PATH || "";

export type SuburbStat = { median: number; yield: number; growth: number; cbd_km: number };

export type Model = {
  version: number;
  generated_at: string;
  features: string[];
  priors: Record<string, number>;
  coefficients: Record<string, number>;
  medians: { land: number; floor: number; bedrooms: number; bathrooms: number };
  city: { median: number; growth_pct: number };
  suburbs: Record<string, SuburbStat>;
  lambda: number | null;
  n_train: number;
  cv_mae_log: number | null;
  cv_mae_pct: number | null;
  r2: number | null;
  confidence: "low" | "medium" | "high";
  band: number;
  fitted: boolean;
};

